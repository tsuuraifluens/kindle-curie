const fs=require('fs');
const { crc16, encCipher, sfcCipher } = require('./build_kindle_click.js');
const orig=fs.readFileSync('analysis/firmware/L1161 L1162.ufw');
const cand=fs.readFileSync('work/our_v18_pnp.ufw');
let pass=0,fail=0;
function check(n,c,x=''){ if(c){pass++;console.log('PASS '+n+' '+x);}else{fail++;console.log('FAIL '+n+' '+x);} }
check('size',cand.length===645184,cand.length);
check('uboot identical',cand.slice(0x4a0,0x4a0+4831).equals(orig.slice(0x4a0,0x4a0+4831)));
check('isd_config identical',cand.slice(0x177f,0x177f+122).equals(orig.slice(0x177f,0x177f+122)));
const e0=Buffer.from(cand.slice(0x40,0x90)); encCipher(e0,0,0x50,0xffff);
check('flash CRC',crc16(cand.slice(0x400,0x400+0xd840*6/6))===0,'(info)');
const flash=cand.slice(0x400,0x400+212992);
check('flash CRC==entry0+4',crc16(flash)===e0.readUInt32LE(4),'0x'+crc16(flash).toString(16));
const h=Buffer.from(cand.slice(0,0x40)); encCipher(h,0,0x40,0xffff);
const num=h.readUInt16LE(8), hs=0x40+num*0x50;
check('list CRC',crc16(cand.slice(0x40,hs))===h.readUInt16LE(2),'0x'+h.readUInt16LE(2).toString(16));
check('header CRC',crc16(h.slice(2,0x40))===h.readUInt16LE(0),'0x'+h.readUInt16LE(0).toString(16));
const dec=Buffer.from(cand.slice(0x400,0x400+0x34000)); sfcCipher(dec,0x2000,0x33cba-0x2000,0x2000,0x190d);
const app=dec.slice(0x2120);
check('app data CRC',crc16(app.slice(0,198824))===dec.readUInt16LE(0x2022),'0x'+dec.readUInt16LE(0x2022).toString(16));
check('app entry hdr CRC',crc16(dec.slice(0x2022,0x2040))===dec.readUInt16LE(0x2020));
check('area data CRC',crc16(dec.slice(0x2020,0x2020+0x30c7a))===dec.readUInt16LE(0x2002));
check('area hdr CRC',crc16(dec.slice(0x2002,0x2020))===dec.readUInt16LE(0x2000));
check('PnP VID',app.slice(0x4168,0x416c).toString('hex')==='04fb7101');
check('PnP PID',app.slice(0x417a,0x417e).toString('hex')==='00fb4304');
check('GAP Kindle-PT',app.slice(0x211c6,0x211cf).toString()==='Kindle-PT');
check('DIS Amazon',app.slice(0x22384,0x2238a).toString()==='Amazon');
check('ADV r6=4',app.slice(0x4d90,0x4d92).toString('hex')==='4670');
check('T1 A',app.slice(0x2289c,0x228a2).toString('hex')==='0200004e0000');
check('T1 B',app.slice(0x228a2,0x228a8).toString('hex')==='0200004b0000');
check('T1 Left/Right',app.slice(0x22908,0x22914).toString('hex')==='0200007000000200006f0000');
console.log(`\nRESULT: ${pass} passed, ${fail} failed`);
