// v21c: composite keyboard+Consumer, 67-byte descriptor, no LED output report.
// Input report remains 8 bytes: modifier + reserved + 4 keys + Consumer usage.
const fs = require('fs');
const { build, defaultPatches } = require('./build_kindle_click.js');

const DESC = Buffer.from([
  0x05, 0x01, 0x09, 0x06, 0xa1, 0x01, 0x85, 0x02,
  0x05, 0x07, 0x19, 0xe0, 0x29, 0xe7, 0x15, 0x00,
  0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
  0x95, 0x01, 0x75, 0x08, 0x81, 0x01,
  0x95, 0x04, 0x75, 0x08, 0x15, 0x00, 0x26, 0xff, 0x00,
  0x05, 0x07, 0x19, 0x00, 0x2a, 0xff, 0x00, 0x81, 0x00,
  0x05, 0x0c, 0x15, 0x00, 0x26, 0xff, 0x03,
  0x19, 0x00, 0x2a, 0xff, 0x03,
  0x75, 0x10, 0x95, 0x01, 0x81, 0x00,
  0xc0,
]);

if (DESC.length !== 67) throw new Error(`descriptor length ${DESC.length}`);

const patches = defaultPatches().filter(
  ([n]) => n !== 'T1 Left BrightDown' && n !== 'T1 Right BrightUp'
);

patches.push(['PnP VID', 0x44ae, Buffer.from([0x00, 0xfb, 0x71, 0x01])]);
patches.push(['PnP PID', 0x44c0, Buffer.from([0x00, 0xfb, 0x43, 0x04])]);
patches.push(['PnP NOP', 0x44ce, Buffer.from([0x00, 0x00])]);
patches.push(['Left Consumer', 0x22908, Buffer.from([0x04, 0x00, 0x70, 0x00, 0x00, 0x00])]);
patches.push(['Right Consumer', 0x2290e, Buffer.from([0x04, 0x00, 0x6f, 0x00, 0x00, 0x00])]);
patches.push(['Descriptor length 67', 0xabbe, Buffer.from([0x30, 0x74])]);
patches.push(['Descriptor pointer 0x1E23450', 0xabc2, Buffer.from([0xc1, 0xff, 0x50, 0x34, 0xe2, 0x01])]);
patches.push(['Consumer usage -> agg+38', 0xc7c6, Buffer.from([0x38, 0x59])]);
patches.push(['Composite descriptor @0x23330', 0x23330, DESC]);

const outPath = process.argv[3] || 'outputs/IINE_Kindle_Click_v21c_Composite.ufw';
const r = build(
  process.argv[2] || 'analysis/firmware/L1161 L1162.ufw',
  outPath,
  { patches }
);
console.log(JSON.stringify({ outPath, descriptorLength: DESC.length, result: r }, null, 2));
